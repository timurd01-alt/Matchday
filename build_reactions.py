"""Build personal Reactions; import writing with --import-text FILE --title TITLE.

Only explicitly published source entries are public. This builder never authors
personal opinions and is independent of generated research and recap posts.
"""
import argparse
import datetime as dt
import html
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent


def build(root=ROOT, output=None):
    root, output = Path(root), Path(output or root)
    entries = []
    for source in sorted((root / 'reactions/source').glob('*.json')):
        post = json.loads(source.read_text(encoding='utf-8'))
        if post.get('status') != 'published':
            continue
        slug = source.stem
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', slug):
            raise ValueError(f'Invalid slug: {slug}')
        dt.date.fromisoformat(post['date'])
        for field in ('title', 'summary', 'author'):
            if not isinstance(post.get(field), str) or not post[field].strip():
                raise ValueError(f'{source}: {field} is required')
        body = post.get('body')
        if not isinstance(body, list) or not body or any(not isinstance(p, str) or not p.strip() for p in body):
            raise ValueError(f'{source}: body must contain paragraphs')
        entries.append(dict(post, slug=slug))
    entries.sort(key=lambda p: (p['date'], p['slug']), reverse=True)
    # Validate every entry before writing any output.
    dest = output / 'reactions'
    dest.mkdir(parents=True, exist_ok=True)
    esc = lambda value: html.escape(str(value), quote=True)
    for p in entries:
        page = f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(p['title'])} | Matchday Reactions</title><meta name="description" content="{esc(p['summary'])}">
<link rel="canonical" href="https://matchdayterminal.com/reactions/{p['slug']}.html">
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Barlow+Condensed:wght@600;700&amp;family=Inter:wght@400;600&amp;family=JetBrains+Mono:wght@400;600&amp;display=swap">
<link rel="stylesheet" href="../styles.css"><link rel="stylesheet" href="../reactions.css"></head>
<body class="reactionArticleBody"><main class="reactionArticle"><nav aria-label="Article navigation"><a href="../?view=reactions">← All reactions</a><a href="../?view=home">Matchday Terminal</a></nav>
<article><div class="reactionKicker">MATCHDAY REACTIONS · PERSONAL REFLECTION</div><h1>{esc(p['title'])}</h1>
<div class="reactionByline">{esc(p['author'])} · <time datetime="{esc(p['date'])}">{esc(p['date'])}</time></div>
<div class="reactionProse">{''.join('<p>'+esc(paragraph)+'</p>' for paragraph in p['body'])}</div></article>
<footer>Personal reflections on college sports and the Matchday model.<br><a class="reactionRead" href="../?view=reactions">More weekly reactions →</a></footer></main></body></html>'''
        (dest / (p['slug'] + '.html')).write_text(page, encoding='utf-8', newline='\n')
    feed = [{k: p[k] for k in ('slug', 'title', 'summary', 'date', 'author')} for p in entries]
    # Escape '<' so authored text cannot terminate an inline script if reused.
    serialized = json.dumps(feed, ensure_ascii=True, indent=2).replace('<', '\\u003c')
    (output / 'reactions-data.js').write_text('/* Generated by build_reactions.py. */\nwindow.MATCHDAY_REACTIONS = ' + serialized + ';\n', encoding='utf-8', newline='\n')
    return feed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--import-text', type=Path, help='Import a UTF-8 plain-text reaction; blank lines separate paragraphs')
    parser.add_argument('--title')
    parser.add_argument('--date', default=dt.date.today().isoformat())
    parser.add_argument('--author', default='Timur')
    parser.add_argument('--summary')
    parser.add_argument('--publish', action='store_true', help='Explicitly mark the imported text ready for publication')
    args = parser.parse_args()
    if args.import_text:
        if not args.title or not args.title.strip():
            parser.error('--title is required for imports')
        dt.date.fromisoformat(args.date)
        slug = args.date + '-' + re.sub(r'[^a-z0-9]+', '-', args.title.lower()).strip('-')
        target = ROOT / 'reactions/source' / (slug + '.json')
        if target.exists():
            parser.error(f'Already exists: {target.name}; edit its source to revise it')
        paragraphs = [p.strip() for p in re.split(r'\n\s*\n', args.import_text.read_text(encoding='utf-8-sig').strip()) if p.strip()]
        if not paragraphs:
            parser.error('The imported file is empty')
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(dict(title=args.title, date=args.date, author=args.author, summary=args.summary or paragraphs[0][:220], status='published' if args.publish else 'draft', body=paragraphs), ensure_ascii=False, indent=2)+'\n', encoding='utf-8', newline='\n')
        print(f'Imported {target.name} as {"published" if args.publish else "draft"}.')
    print(f'Built {len(build(output=args.output))} reactions.')


if __name__ == '__main__':
    main()
